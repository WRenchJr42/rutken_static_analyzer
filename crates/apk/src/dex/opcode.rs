pub fn opcode_width(op:u8)->usize {

    match op {

        // 10x
        0x00 | 0x0e | 0x0f | 0x12 => 1,

        // 21x / 21c / 22x
        0x01 | 0x04 | 0x07 | 0x0a | 0x13 | 0x1a | 0x1f | 0x20 | 0x21 | 0x22 | 0x54..=0x6d => 2,

        // 31i / 35c
        0x03 | 0x24 | 0x25 | 0x6e..=0x72 => 3,

        0x14 => 2,

        _ => 1,
    }
}
